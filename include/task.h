#pragma once
#include <string>

/**
 * @file task.h
 * @brief Содержит перечисления приоритетов и статусов, а также структуру задачи.
 */

/**
 * @brief Определяет уровни приоритета задачи.
 */
enum Priority
{
    LOW = 0,       ///< Низкий приоритет.
    MEDIUM = 1,    ///< Средний приоритет.
    HIGH = 2,      ///< Высокий приоритет.
    CRITICAL = 3   ///< Критический приоритет.
};

/**
 * @brief Определяет возможные статусы задачи.
 */
enum Status
{
    OPEN = 0,         ///< Задача ожидает выполнения.
    IN_PROGRESS = 1,  ///< Задача находится в процессе выполнения.
    COMPLETED = 2     ///< Задача завершена.
};

/**
 * @brief Представляет задачу в трекере.
 */
struct Task
{
    int id;             ///< Уникальный идентификатор задачи.
    std::string title;  ///< Название задачи.
    Priority priority;  ///< Приоритет задачи.
    Status status;      ///< Текущий статус задачи.
};
